    })
    Assert-R23D2Exact ($lines.Count -eq 1) (
        "QSDK-R23D2 expected one '$Prefix' pass marker, observed $($lines.Count)"
    )
}

function Invoke-R23D2Gate {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$PassPrefix,
        [string[]]$AdditionalArguments = @()
    )
    $arguments = @("-NoLogo", "-NoProfile", "-File", $Path) + $AdditionalArguments
    $result = Invoke-R23D2Process `
        -FileName "pwsh" `
        -Arguments $arguments `
        -WorkingDirectory $repoRoot `
        -TimeoutSeconds $GateTimeoutSeconds
    if ($result.stdout) { Write-Host $result.stdout.TrimEnd() }
    if ($result.stderr) { Write-Host $result.stderr.TrimEnd() }
    Assert-R23D2Exact (
        -not [bool]$result.timed_out -and [int]$result.exit_code -eq 0
    ) "QSDK-R23D2 gate failed: $Path"
    Assert-R23D2PassMarker -Text $result.stdout -Prefix $PassPrefix
    return $result
}

