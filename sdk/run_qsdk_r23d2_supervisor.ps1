function Invoke-R23D2PhysicalCell {
    param(
        [Parameter(Mandatory)][string]$EngineId,
        [Parameter(Mandatory)][string]$ArmId,
        [Parameter(Mandatory)][string]$SourceCommit,
        [Parameter(Mandatory)][string]$AttemptPayloadPath,
        [Parameter(Mandatory)][string]$Token,
        [Parameter(Mandatory)][string]$CellRoot
    )
    [void][IO.Directory]::CreateDirectory($CellRoot)
    $cellId = "$EngineId`__$ArmId"
    $environment = [ordered]@{
        SPORESPORE_QSDK_R23D2_ATTEMPT = $AttemptPayloadPath
        SPORESPORE_QSDK_R23D2_TOKEN = $Token
        SPORESPORE_QSDK_R23D2_CELL = $cellId
        SPORESPORE_QSDK_R23D2_ENGINE = $EngineId
    }
    $fileName = ""
    $arguments = @()
    $workingDirectory = $repoRoot
    $successPrefix = ""
    $failurePrefix = ""
    if ($EngineId -ceq "godot_jolt") {
        $fileName = $Godot
        $environment.APPDATA = Join-Path $CellRoot "appdata"
        $environment.LOCALAPPDATA = Join-Path $CellRoot "localappdata"
        [void][IO.Directory]::CreateDirectory($environment.APPDATA)
        [void][IO.Directory]::CreateDirectory($environment.LOCALAPPDATA)
        $arguments = @(
            "--headless", "--path", $repoRoot, "--script",
            $godotWorkerResource, "--", "physical", $ArmId, $SourceCommit
        )
        $successPrefix = "QSDK_R23D2_GODOT_JOLT_CELL "
        $failurePrefix = "QSDK_R23D2_GODOT_JOLT_FAILURE "
    } elseif ($EngineId -ceq "rapier_parry") {
        $fileName = $rapierBinaryPath
        $arguments = @("--arm", $ArmId, "--source-commit", $SourceCommit)
        $successPrefix = "QSDK_R23D2_RAPIER_CELL "
        $failurePrefix = "QSDK_R23D2_RAPIER_FAILURE "
    } elseif ($EngineId -ceq "mujoco") {
        $fileName = $mujocoPython
        $workingDirectory = $mujocoRoot
        $environment.SPORESPORE_LOCOMOTION_LIBRARY = $coreLibraryPath
        $environment.PYTHONPATH = $pythonCoreRoot
        $arguments = @(
            "-m", "sporespore_mujoco_adapter.qsdk_r23d2_heading_response",
            "--arm", $ArmId, "--source-commit", $SourceCommit
        )
        $successPrefix = "QSDK_R23D2_MUJOCO_CELL "
        $failurePrefix = "QSDK_R23D2_MUJOCO_FAILURE "
    } else { throw "QSDK-R23D2 unknown physical engine: $EngineId" }

    $launchSucceeded = $false
    try {
        $result = Invoke-R23D2Process `
            -FileName $fileName `
            -Arguments $arguments `
            -WorkingDirectory $workingDirectory `
            -Environment $environment `
            -TimeoutSeconds $CellTimeoutSeconds
        $launchSucceeded = $true
    } catch {
        $result = [ordered]@{
            exit_code = -1
            timed_out = $false
            duration_seconds = 0.0
            stdout = ""
            stderr = "SUPERVISOR_PROCESS_START_EXCEPTION:$($_.Exception.Message)"
        }
    }
    $logPath = Join-Path $CellRoot "engine.log"
    [IO.File]::WriteAllText(
        $logPath,
        [string]$result.stdout + [string]$result.stderr,
        [Text.UTF8Encoding]::new($false)
    )
    $logCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $logPath `
        -MediaType "text/plain"

    $successLines = @([string]$result.stdout -split "`r?`n" | Where-Object {
        $_.StartsWith($successPrefix, [StringComparison]::Ordinal)
    })
    $failureLines = @([string]$result.stdout -split "`r?`n" | Where-Object {
        $_.StartsWith($failurePrefix, [StringComparison]::Ordinal)
    })
    $terminal = $null
    $markerKind = "supervisor_process_failure"
    try {
        if (
            $launchSucceeded -and -not [bool]$result.timed_out -and
            [int]$result.exit_code -eq 0 -and
            $successLines.Count -eq 1 -and $failureLines.Count -eq 0
        ) {
            $terminal = $successLines[0].Substring($successPrefix.Length) |
                ConvertFrom-Json -AsHashtable -Depth 100
            $markerKind = "successful_report"
        } elseif (
            $launchSucceeded -and -not [bool]$result.timed_out -and
            [int]$result.exit_code -ne 0 -and
            $failureLines.Count -eq 1 -and $successLines.Count -eq 0
        ) {
            $terminal = $failureLines[0].Substring($failurePrefix.Length) |
                ConvertFrom-Json -AsHashtable -Depth 100
            $markerKind = "worker_failure"
        }
    } catch {
        $terminal = $null
    }
    if ($null -eq $terminal) {
        $terminal = [ordered]@{
            schema_version = "sporespore_qsdk_r23d2_supervisor_process_failure_v1"
            campaign_id = $campaignId
            gate_id = $gateId
            cell_id = $cellId
            engine_id = $EngineId
            arm_id = $ArmId
            source_commit = $SourceCommit
            process_launch_succeeded = $launchSucceeded
            process_exit_code = [int]$result.exit_code
            process_timed_out = [bool]$result.timed_out
            success_marker_count = $successLines.Count
            failure_marker_count = $failureLines.Count
            world_attempt_count_known = $false
            world_build_count_known = $false
            engine_log_sha256 = [string]$logCas.sha256
            physical_acceptance_authority = $false
        }
    }
    $terminalPath = Join-Path $CellRoot "terminal-entry.json"
    Write-R23D2NewJson -Path $terminalPath -Value $terminal
    $terminalCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $terminalPath `
        -MediaType "application/json"
    $entryEvaluation = Invoke-R23D2EntryEvaluator `
        -EntryPath ([string]$terminalCas.payload_path)
    $evaluationPath = Join-Path $CellRoot "entry-evaluation.json"
    Write-R23D2NewJson -Path $evaluationPath -Value $entryEvaluation.evaluation
    $evaluationCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $evaluationPath `
        -MediaType "application/json"
    return [ordered]@{
        cell_id = $cellId
        engine_id = $EngineId
        arm_id = $ArmId
        process_launch_succeeded = $launchSucceeded
        process_exit_code = [int]$result.exit_code
        process_timed_out = [bool]$result.timed_out
        process_duration_seconds = [double]$result.duration_seconds
        terminal_marker_kind = $markerKind
        terminal_entry_cas = $terminalCas
        entry_evaluation = $entryEvaluation.evaluation
        entry_evaluation_cas = $evaluationCas
        engine_log_cas = $logCas
        physical_acceptance_authority = $false
    }
}

function Invoke-R23D2PhysicalCampaign {
    param(
        [Parameter(Mandatory)]$Source,
        [Parameter(Mandatory)]$Attestation,
        [Parameter(Mandatory)]$ZeroWorldReceipt
    )
    $sourceAfterPreflight = Get-SporeSporeAttestationSourceIdentity `
        -RepoRoot $repoRoot `
        -RequireCleanPushedLive
    Assert-R23D2Exact (
        [string]$sourceAfterPreflight.commit -ceq [string]$Source.commit -and
        [string]$sourceAfterPreflight.tree_git_oid -ceq [string]$Source.tree_git_oid
    ) "QSDK-R23D2 source changed during zero-world preflight"
    # The gates are allowed to compile, but they may not change any runtime
    # bytes that the one-shot campaign would consume. This second full check is
    # deliberately after every zero-world gate and before CAS publication or
    # attempt creation.
    Assert-R23D2FrozenBindings
    $evidenceRoot = Get-SporeSporeArtifactEvidenceRoot -RepoRoot $repoRoot
    $prior = @(Get-ChildItem -LiteralPath $evidenceRoot -Directory |
        Where-Object { $_.Name -like "qsdk-r23d2-*" })
    Assert-R23D2Exact ($prior.Count -eq 0) (
        "QSDK-R23D2 one-shot identity already exists; rerun forbidden"
    )
    $resolvedOutput = if ([string]::IsNullOrWhiteSpace($OutputRoot)) {
        Join-Path $evidenceRoot (
            "qsdk-r23d2-" + [DateTime]::UtcNow.ToString("yyyyMMddTHHmmssZ")
        )
    } else { [IO.Path]::GetFullPath($OutputRoot) }
    $prefix = $evidenceRoot.TrimEnd("\", "/") + [IO.Path]::DirectorySeparatorChar
    Assert-R23D2Exact (
        $resolvedOutput.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase) -and
        -not (Test-Path -LiteralPath $resolvedOutput)
    ) "QSDK-R23D2 output must be a new directory under $evidenceRoot"

    $inputCas = Publish-R23D2InputArtifacts `
        -AttestationPath $FullConformanceAttestation
    [void][IO.Directory]::CreateDirectory($resolvedOutput)
    $completionPath = Join-Path $resolvedOutput "completion.json"
    $attemptConsumed = $false
    try {
        $token = [guid]::NewGuid().ToString("N")
        $attempt = [ordered]@{
            schema_version = "sporespore_qsdk_r23d2_attempt_v1"
            attempt_id = [guid]::NewGuid().ToString("N")
            campaign_id = $campaignId
            gate_id = $gateId
            contract_sha256 = Get-R23D2RawSha256 $contractPath
            freeze_sha256 = Get-R23D2RawSha256 $freezePath
            source_commit = [string]$Source.commit
            origin_main_commit = [string]$Source.origin_main
            live_main_commit = [string]$Source.live_github_main
            authorization_token = $token
            physical_execution_authorized = $true
            single_use_supervisor_authorization = $true
            source_worktree_clean = $true
            source_matches_live_github_main = $true
            operation_lock_held = $true
            full_godot_attestation_valid = $true
            full_godot_attestation_sha256 = [string]$Attestation.sha256
            content_addressed_inputs_retained = $true
            content_addressed_inputs = $inputCas
            complete_zero_world_gate_passed = $true
            zero_world_receipt = $ZeroWorldReceipt
            one_shot_attempt_unconsumed = $true
            ordered_cell_ids = $orderedCellIds
            replacement_or_selective_rerun_permitted = $false
            physical_acceptance_authority = $false
        }
        $attemptPath = Join-Path $resolvedOutput "attempt.json"
        Write-R23D2NewJson -Path $attemptPath -Value $attempt
        $attemptCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath $attemptPath `
            -MediaType "application/json"
        $attemptConsumed = $true

        $cells = [Collections.Generic.List[object]]::new()
        foreach ($cellId in $orderedCellIds) {
            $parts = $cellId -split "__", 2
            $cells.Add((Invoke-R23D2PhysicalCell `
                -EngineId $parts[0] `
                -ArmId $parts[1] `
                -SourceCommit ([string]$Source.commit) `
                -AttemptPayloadPath ([string]$attemptCas.payload_path) `
                -Token $token `
                -CellRoot (Join-Path $resolvedOutput $cellId)))
        }
        $terminalPaths = @($cells | ForEach-Object {
            [string]$_.terminal_entry_cas.payload_path
        })
        $aggregateInput = [ordered]@{
            schema_version = "sporespore_qsdk_r23d2_aggregate_input_v1"
            ordered_cell_ids = $orderedCellIds
            retained_terminal_entry_count = $terminalPaths.Count
            ordered_terminal_entry_cas = @($cells | ForEach-Object {
                $_.terminal_entry_cas
            })
            physical_acceptance_authority = $false
        }
        $aggregateInputPath = Join-Path $resolvedOutput "aggregate-input.json"
        Write-R23D2NewJson -Path $aggregateInputPath -Value $aggregateInput
        $aggregateInputCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath $aggregateInputPath `
            -MediaType "application/json"
        $aggregate = Invoke-R23D2Aggregate -EntryPaths $terminalPaths
        $aggregateEvaluationPath = Join-Path $resolvedOutput "aggregate-evaluation.json"
        Write-R23D2NewJson `
            -Path $aggregateEvaluationPath `
            -Value $aggregate.evaluation
        $aggregateEvaluationCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath $aggregateEvaluationPath `
            -MediaType "application/json"
        $classification = [string]$aggregate.evaluation.result_classification
        $valid = (
            $cells.Count -eq 9 -and
            $terminalPaths.Count -eq 9 -and
            [bool]$aggregate.evaluation.aggregate_valid -and
            $classification -in @("valid_positive", "valid_negative")
        )
        $report = [ordered]@{
            schema_version = "sporespore_qsdk_r23d2_campaign_report_v1"
            campaign_id = $campaignId
            gate_id = $gateId
