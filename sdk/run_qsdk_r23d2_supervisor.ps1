function Publish-R23D2InputArtifacts {
    param([Parameter(Mandatory)][string]$AttestationPath)
    $receipts = [ordered]@{}
    foreach ($binding in @($freeze.source_bindings)) {
        $path = Join-Path $repoRoot ([string]$binding.path)
        $receipts[[string]$binding.name] =
            Publish-SporeSporeContentAddressedArtifact `
                -RepoRoot $repoRoot `
                -ArtifactPath $path `
                -MediaType ([string]$binding.media_type)
    }
    $receipts.physical_freeze = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $freezePath `
        -MediaType "application/json"
    foreach ($runtime in @($freeze.attempt_runtime_artifacts)) {
        $path = if ([bool]$runtime.repo_relative) {
            Join-Path $repoRoot ([string]$runtime.path)
        } else { [string]$runtime.path }
        $receipts[[string]$runtime.name] =
            Publish-SporeSporeContentAddressedArtifact `
                -RepoRoot $repoRoot `
                -ArtifactPath $path `
                -MediaType ([string]$runtime.media_type)
    }
    $receipts.full_godot_attestation =
        Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath $AttestationPath `
            -MediaType "application/json"
    return $receipts
}

function Assert-R23D2FrozenBindings {
    foreach ($binding in @($freeze.source_bindings)) {
        $path = Join-Path $repoRoot ([string]$binding.path)
        Assert-R23D2Exact (
            (Test-Path -LiteralPath $path -PathType Leaf) -and
            [string]$binding.raw_sha256 -ceq (Get-R23D2RawSha256 $path)
        ) "QSDK-R23D2 source binding changed: $([string]$binding.path)"
    }
    foreach ($runtime in @($freeze.external_runtime_bindings)) {
        $path = [IO.Path]::GetFullPath([string]$runtime.path)
        Assert-R23D2Exact (
            (Test-Path -LiteralPath $path -PathType Leaf) -and
            [string]$runtime.raw_sha256 -ceq (Get-R23D2RawSha256 $path)
        ) "QSDK-R23D2 external runtime binding changed: $path"
    }
    foreach ($runtime in @($freeze.attempt_runtime_artifacts)) {
        $path = if ([bool]$runtime.repo_relative) {
            Join-Path $repoRoot ([string]$runtime.path)
        } else { [IO.Path]::GetFullPath([string]$runtime.path) }
        Assert-R23D2Exact (
            (Test-Path -LiteralPath $path -PathType Leaf) -and
            [string]$runtime.raw_sha256 -ceq (Get-R23D2RawSha256 $path)
        ) "QSDK-R23D2 attempt runtime binding changed: $path"
    }
}

