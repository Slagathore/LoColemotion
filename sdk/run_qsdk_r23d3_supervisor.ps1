function Invoke-R23D3PhysicalCell {
    param(
        [Parameter(Mandatory)][string]$StageId,
        [Parameter(Mandatory)][string]$EngineId,
        [Parameter(Mandatory)][string]$OnsetId,
        [Parameter(Mandatory)][string]$ArmId,
        [Parameter(Mandatory)][string]$SourceCommit,
        [Parameter(Mandatory)][string]$FreezePayloadPath,
        [Parameter(Mandatory)][string]$AttemptPayloadPath,
        [Parameter(Mandatory)][string]$Token,
        [Parameter(Mandatory)][string]$AttemptRoot,
        [Parameter(Mandatory)][string]$CellRoot,
        [Parameter(Mandatory)]$RuntimeArtifacts
    )
    [void][IO.Directory]::CreateDirectory($CellRoot)
    $cellId = "$EngineId`__$OnsetId`__$ArmId"
    $environment = [ordered]@{
        SPORESPORE_QSDK_R23D3_FREEZE = $FreezePayloadPath
        SPORESPORE_QSDK_R23D3_ATTEMPT = $AttemptPayloadPath
        SPORESPORE_QSDK_R23D3_TOKEN = $Token
        SPORESPORE_QSDK_R23D3_STAGE = $StageId
        SPORESPORE_QSDK_R23D3_CELL = $cellId
        SPORESPORE_QSDK_R23D3_ENGINE = $EngineId
        SPORESPORE_QSDK_R23D3_ATTEMPT_ROOT = $AttemptRoot
        SPORESPORE_QSDK_R23D3_PYTHON = $Python
        SPORESPORE_QSDK_R23D3_POWERSHELL = $PowerShell
    }
    $fileName = ""
    $arguments = @()
    $workingDirectory = $repoRoot
    $successPrefix = ""
    $failurePrefix = ""
    if ($EngineId -ceq "godot_jolt") {
        $fileName = $Godot
        $environment.APPDATA = Join-Path $CellRoot "appdata"
        $environment.LOCALAPPDATA = Join-Path $CellRoot "localappdata"
        [void][IO.Directory]::CreateDirectory($environment.APPDATA)
        [void][IO.Directory]::CreateDirectory($environment.LOCALAPPDATA)
        $arguments = @(
            "--headless", "--path", $repoRoot,
            "--log-file", (Join-Path $CellRoot "godot.log"),
            "--script", $godotWorkerResource, "--",
            "--stage", $StageId, "--onset", $OnsetId, "--arm", $ArmId,
            "--source-commit", $SourceCommit
        )
        $successPrefix = "QSDK_R23D3_GODOT_JOLT_CELL "
        $failurePrefix = "QSDK_R23D3_GODOT_JOLT_FAILURE "
    } elseif ($EngineId -ceq "rapier_parry") {
        $fileName = [string]$RuntimeArtifacts.rapier_worker
        $arguments = @(
            "--stage", $StageId, "--onset", $OnsetId, "--arm", $ArmId,
            "--source-commit", $SourceCommit
        )
        $successPrefix = "QSDK_R23D3_RAPIER_CELL "
        $failurePrefix = "QSDK_R23D3_RAPIER_FAILURE "
    } elseif ($EngineId -ceq "mujoco") {
        $fileName = $mujocoPython
        $workingDirectory = $repoRoot
        $environment.SPORESPORE_LOCOMOTION_LIBRARY =
            [string]$RuntimeArtifacts.locomotion_core
        $environment.PYTHONPATH = (
            $mujocoRoot + [IO.Path]::PathSeparator + $pythonCoreRoot
        )
        $arguments = @(
            "-m", "sporespore_mujoco_adapter.qsdk_r23d3_phase_balanced",
            "--stage", $StageId, "--onset", $OnsetId, "--arm", $ArmId,
            "--source-commit", $SourceCommit
        )
        $successPrefix = "QSDK_R23D3_MUJOCO_CELL "
        $failurePrefix = "QSDK_R23D3_MUJOCO_FAILURE "
    } else {
        throw "QSDK-R23D3 unknown physical engine: $EngineId"
    }

    Write-Host "QSDK_R23D3_CELL_BEGIN stage=$StageId cell=$cellId"
    $launchSucceeded = $false
    try {
        $result = Invoke-R23D3Process `
            -FileName $fileName `
            -Arguments $arguments `
            -WorkingDirectory $workingDirectory `
            -Environment $environment `
            -TimeoutSeconds $CellTimeoutSeconds
        $launchSucceeded = $true
    } catch {
        $result = [ordered]@{
            exit_code = -1
            timed_out = $false
            duration_seconds = 0.0
            stdout = ""
            stderr = "SUPERVISOR_PROCESS_START_EXCEPTION:$($_.Exception.Message)"
        }
    }
    $logPath = Join-Path $CellRoot "engine.log"
    [IO.File]::WriteAllText(
        $logPath,
        [string]$result.stdout + [string]$result.stderr,
        [Text.UTF8Encoding]::new($false)
    )
    $logCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $logPath `
        -MediaType "text/plain"

    $successLines = @([string]$result.stdout -split "`r?`n" | Where-Object {
        $_.StartsWith($successPrefix, [StringComparison]::Ordinal)
    })
    $failureLines = @([string]$result.stdout -split "`r?`n" | Where-Object {
        $_.StartsWith($failurePrefix, [StringComparison]::Ordinal)
    })
    $terminal = $null
    $markerKind = "supervisor_process_failure"
    try {
        if (
            $launchSucceeded -and -not [bool]$result.timed_out -and
            [int]$result.exit_code -eq 0 -and
            $successLines.Count -eq 1 -and $failureLines.Count -eq 0
        ) {
            $terminal = $successLines[0].Substring($successPrefix.Length) |
                ConvertFrom-Json -AsHashtable -Depth 100
            $markerKind = "successful_report"
        } elseif (
            $launchSucceeded -and -not [bool]$result.timed_out -and
            [int]$result.exit_code -ne 0 -and
            $failureLines.Count -eq 1 -and $successLines.Count -eq 0
        ) {
            $terminal = $failureLines[0].Substring($failurePrefix.Length) |
                ConvertFrom-Json -AsHashtable -Depth 100
            $markerKind = "worker_failure"
        }
    } catch {
        $terminal = $null
    }
    if ($null -eq $terminal) {
        $terminal = [ordered]@{
            schema_version = "sporespore_qsdk_r23d3_supervisor_process_failure_v1"
            campaign_id = $campaignId
            gate_id = $gateId
            stage_id = $StageId
            cell_id = $cellId
            engine_id = $EngineId
            onset_id = $OnsetId
            arm_id = $ArmId
            source_commit = $SourceCommit
            process_launch_succeeded = $launchSucceeded
            process_exit_code = [int]$result.exit_code
            process_timed_out = [bool]$result.timed_out
            success_marker_count = $successLines.Count
            failure_marker_count = $failureLines.Count
            world_attempt_count_known = $false
            world_build_count_known = $false
            engine_log_sha256 = [string]$logCas.sha256
            physical_acceptance_authority = $false
        }
    }
    $terminalPath = Join-Path $CellRoot "terminal-entry.json"
    Write-R23D3NewJson -Path $terminalPath -Value $terminal
    $terminalCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $terminalPath `
        -MediaType "application/json"
    Write-Host (
        "QSDK_R23D3_CELL_RETAINED stage=$StageId cell=$cellId " +
        "marker=$markerKind terminal_sha256=$([string]$terminalCas.sha256)"
    )
    return [ordered]@{
        stage_id = $StageId
        cell_id = $cellId
        engine_id = $EngineId
        onset_id = $OnsetId
        arm_id = $ArmId
        process_launch_succeeded = $launchSucceeded
        process_exit_code = [int]$result.exit_code
        process_timed_out = [bool]$result.timed_out
        process_duration_seconds = [double]$result.duration_seconds
        terminal_marker_kind = $markerKind
        terminal_entry_cas = $terminalCas
        engine_log_cas = $logCas
        physical_acceptance_authority = $false
    }
}

