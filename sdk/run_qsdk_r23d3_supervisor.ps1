function Invoke-R23D3PhysicalCampaign {
    param(
        [Parameter(Mandatory)]$Source,
        [Parameter(Mandatory)]$Attestation,
        [Parameter(Mandatory)]$ZeroWorldReceipt,
        [Parameter(Mandatory)]$Implementation
    )
    $sourceAfterPreflight = Get-SporeSporeAttestationSourceIdentity `
        -RepoRoot $repoRoot `
        -RequireCleanPushedLive
    Assert-R23D3Exact (
        [string]$sourceAfterPreflight.commit -ceq [string]$Source.commit -and
        [string]$sourceAfterPreflight.tree_git_oid -ceq [string]$Source.tree_git_oid
    ) "QSDK-R23D3 source changed during the zero-world gate"
    Assert-R23D3Exact (
        [string](Invoke-R23D3Git @("status", "--porcelain=v1", "--untracked-files=all")) `
            -ceq ""
    ) "QSDK-R23D3 physical source is not clean after the zero-world gate"

    $evidenceRoot = Get-SporeSporeArtifactEvidenceRoot -RepoRoot $repoRoot
    $prior = @(Get-ChildItem -LiteralPath $evidenceRoot -Directory |
        Where-Object {
            $_.Name -like "qsdk-r23d3-*" -and (
                (Test-Path -LiteralPath (Join-Path $_.FullName "stage-a-authorization.json")) -or
                (Test-Path -LiteralPath (Join-Path $_.FullName "completion.json"))
            )
        })
    Assert-R23D3Exact ($prior.Count -eq 0) (
        "QSDK-R23D3 one-shot identity already exists; rerun is forbidden"
    )
    $resolvedOutput = if ([string]::IsNullOrWhiteSpace($OutputRoot)) {
        Join-Path $evidenceRoot (
            "qsdk-r23d3-" + [DateTime]::UtcNow.ToString("yyyyMMddTHHmmssZ")
        )
    } else { [IO.Path]::GetFullPath($OutputRoot) }
    $evidencePrefix = $evidenceRoot.TrimEnd("\", "/") +
        [IO.Path]::DirectorySeparatorChar
    Assert-R23D3Exact (
        $resolvedOutput.StartsWith(
            $evidencePrefix, [StringComparison]::OrdinalIgnoreCase
        ) -and
        -not (Test-Path -LiteralPath $resolvedOutput)
    ) "QSDK-R23D3 output must be a new directory under $evidenceRoot"
    [void][IO.Directory]::CreateDirectory($resolvedOutput)

    $attemptConsumed = $false
    $completionPath = Join-Path $resolvedOutput "completion.json"
    try {
        . $runtimeMaterializationPath
        Assert-R23D3Exact ($null -ne (Get-Command `
            -Name Initialize-SporeSporeR23D3AttemptRuntimeArtifacts `
            -CommandType Function -ErrorAction SilentlyContinue)) (
            "QSDK-R23D3 reproducible runtime helper surface is missing"
        )
        $materialization = Initialize-SporeSporeR23D3AttemptRuntimeArtifacts `
            -RepoRoot $repoRoot `
            -SourceCommit ([string]$Source.commit) `
            -TargetRoot (Join-Path $sdkRoot "target")
        $runtimeArtifacts = Get-R23D3RuntimeArtifacts $materialization
        $runtimeMap = [ordered]@{
            locomotion_core = [string]$materialization.artifacts.locomotion_core
            godot_adapter = [string]$materialization.artifacts.godot_adapter
            rapier_worker = [string]$materialization.artifacts.rapier_worker
        }
        $sourceBindings = Get-R23D3SourceBindings $Implementation
        $externalRuntimeBindings = Get-R23D3ExternalRuntimeBindings
        $inputCas = Publish-R23D3BoundInputs `
            -SourceBindings $sourceBindings `
            -RuntimeArtifacts $runtimeArtifacts `
            -ExternalRuntimeBindings $externalRuntimeBindings `
            -AttestationPath $FullConformanceAttestation

        $freeze = [ordered]@{
            schema_version = "sporespore_qsdk_r23d3_physical_freeze_v1"
            status = "frozen_supervisor_only_physical_authorized"
            campaign_id = $campaignId
            gate_id = $gateId
            preregistration_raw_sha256 = Get-R23D3RawSha256 $preregistrationPath
            implementation_contract_raw_sha256 = Get-R23D3RawSha256 $implementationPath
            source_commit = [string]$Source.commit
            source_tree_git_oid = [string]$Source.tree_git_oid
            origin_main_commit = [string]$Source.origin_main
            live_github_main_commit = [string]$Source.live_github_main
            source_bindings = $sourceBindings
            runtime_artifacts = $runtimeArtifacts
            external_runtime_bindings = $externalRuntimeBindings
            content_addressed_inputs = $inputCas
            full_godot_attestation_sha256 = [string]$Attestation.sha256
            complete_zero_world_gate_passed = $true
            zero_world_receipt = $ZeroWorldReceipt
            declared_stage_a_world_count = 8
            declared_stage_b_world_count_if_selected = 9
            serial_execution_required = $true
            single_supervisor_attempt_required = $true
            stage_a_reports_may_substitute_for_stage_b = $false
            replacement_or_selective_rerun_permitted = $false
            source_checkout_bytes_equal_git_blobs = $true
            reproducible_runtime_materialization_passed = $true
            physical_execution_authorized = $true
            physical_acceptance_authority = $false
        }
        $freezePath = Join-Path $resolvedOutput "physical-freeze.json"
        Write-R23D3NewJson -Path $freezePath -Value $freeze
        $freezeCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath $freezePath `
            -MediaType "application/json"
        Assert-R23D3FrozenBindings $freeze

        $attemptId = [guid]::NewGuid().ToString("N")
        $stageAToken = [guid]::NewGuid().ToString("N")
        $stageAAuthorizationPath = Join-Path $resolvedOutput "stage-a-authorization.json"
        $stageAAuthorizationCas = New-R23D3StageAuthorization `
            -Path $stageAAuthorizationPath `
            -AttemptId $attemptId `
            -Token $stageAToken `
            -SourceCommit ([string]$Source.commit) `
            -FreezeSha256 ([string]$freezeCas.sha256) `
            -AttemptRoot $resolvedOutput `
            -OrderedStageACellIds $stageACellIds `
            -OrderedStageBCellIds @() `
            -SelectedOnsetId "NONE" `
            -StageAuthorizationId "stage_a" `
            -InputCas $inputCas `
            -ZeroWorldReceipt $ZeroWorldReceipt `
            -AttestationSha256 ([string]$Attestation.sha256)
        $attemptConsumed = $true

        $stageACells = [Collections.Generic.List[object]]::new()
        foreach ($cellId in $stageACellIds) {
            $parts = $cellId -split "__", 3
            $stageACells.Add((Invoke-R23D3PhysicalCell `
                -StageId $stageAId `
                -EngineId "mujoco" `
                -OnsetId $parts[1] `
                -ArmId $parts[2] `
                -SourceCommit ([string]$Source.commit) `
                -FreezePayloadPath ([string]$freezeCas.payload_path) `
                -AttemptPayloadPath ([string]$stageAAuthorizationCas.payload_path) `
                -Token $stageAToken `
                -AttemptRoot $resolvedOutput `
                -CellRoot (Join-Path $resolvedOutput ("stage-a\" + $cellId)) `
                -RuntimeArtifacts $runtimeMap))
        }
        $stageAPaths = @($stageACells | ForEach-Object {
            [string]$_.terminal_entry_cas.payload_path
        })
        $stageAManifestPath = Join-Path $resolvedOutput "stage-a-terminal-paths.json"
        Write-R23D3NewJson -Path $stageAManifestPath -Value $stageAPaths
        $stageAManifestCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $stageAManifestPath `
            -MediaType "application/json"
        $stageAEvaluationResult = Invoke-R23D3Evaluation `
            -Kind "stage-a" -EntryPaths $stageAPaths
        $stageAEvaluationPath = Join-Path $resolvedOutput "stage-a-evaluation.json"
        Write-R23D3NewJson `
            -Path $stageAEvaluationPath `
            -Value $stageAEvaluationResult.evaluation
        $stageAEvaluationCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $stageAEvaluationPath `
            -MediaType "application/json"

        $stageBCells = [Collections.Generic.List[object]]::new()
        $stageBAuthorizationCas = $null
        $selectedOnset = [string]$stageAEvaluationResult.evaluation.selected_onset_id
        if ([bool]$stageAEvaluationResult.evaluation.stage_b_launch_authorized) {
            Assert-R23D3Exact (
                [bool]$stageAEvaluationResult.evaluation.valid -and
                $selectedOnset -cin $onsetOrder -and
                [int]$stageAEvaluationResult.process.exit_code -eq 0
            ) "QSDK-R23D3 Stage B authorization state is inconsistent"
            $stageBCellIds = Get-R23D3StageBCellIds $selectedOnset
            $stageBToken = [guid]::NewGuid().ToString("N")
            $stageBAuthorizationPath = Join-Path `
                $resolvedOutput `
                "stage-b-authorization.json"
            $stageBAuthorizationCas = New-R23D3StageAuthorization `
                -Path $stageBAuthorizationPath `
                -AttemptId $attemptId `
                -Token $stageBToken `
                -SourceCommit ([string]$Source.commit) `
                -FreezeSha256 ([string]$freezeCas.sha256) `
                -AttemptRoot $resolvedOutput `
                -OrderedStageACellIds $stageACellIds `
                -OrderedStageBCellIds $stageBCellIds `
                -SelectedOnsetId $selectedOnset `
                -StageAuthorizationId "stage_b" `
                -InputCas $inputCas `
                -ZeroWorldReceipt $ZeroWorldReceipt `
                -AttestationSha256 ([string]$Attestation.sha256) `
                -ParentAuthorizationSha256 ([string]$stageAAuthorizationCas.sha256)
            foreach ($cellId in $stageBCellIds) {
                $parts = $cellId -split "__", 3
                $stageBCells.Add((Invoke-R23D3PhysicalCell `
                    -StageId $stageBId `
                    -EngineId $parts[0] `
                    -OnsetId $parts[1] `
                    -ArmId $parts[2] `
                    -SourceCommit ([string]$Source.commit) `
                    -FreezePayloadPath ([string]$freezeCas.payload_path) `
                    -AttemptPayloadPath ([string]$stageBAuthorizationCas.payload_path) `
                    -Token $stageBToken `
                    -AttemptRoot $resolvedOutput `
                    -CellRoot (Join-Path $resolvedOutput ("stage-b\" + $cellId)) `
                    -RuntimeArtifacts $runtimeMap))
            }
        } else {
            Assert-R23D3Exact (
                -not [bool]$stageAEvaluationResult.evaluation.valid -or
                $selectedOnset -ceq "NONE"
            ) "QSDK-R23D3 Stage B was withheld for an unknown selector state"
        }

        $stageBPaths = @($stageBCells | ForEach-Object {
            [string]$_.terminal_entry_cas.payload_path
        })
        $stageBManifestPath = Join-Path $resolvedOutput "stage-b-terminal-paths.json"
        Write-R23D3NewJson -Path $stageBManifestPath -Value $stageBPaths
        $stageBManifestCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $stageBManifestPath `
            -MediaType "application/json"
        $completeResult = Invoke-R23D3Evaluation `
            -Kind "complete" `
            -StageAManifest ([string]$stageAManifestCas.payload_path) `
            -StageBManifest ([string]$stageBManifestCas.payload_path)
        $completeEvaluationPath = Join-Path $resolvedOutput "complete-evaluation.json"
        Write-R23D3NewJson `
            -Path $completeEvaluationPath `
            -Value $completeResult.evaluation
        $completeEvaluationCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $completeEvaluationPath `
            -MediaType "application/json"

        $classification = [string]$completeResult.evaluation.classification
        $validResult = -not $classification.StartsWith(
            "invalid", [StringComparison]::Ordinal
        )
        $report = [ordered]@{
            schema_version = "sporespore_qsdk_r23d3_campaign_report_v1"
            campaign_id = $campaignId
            gate_id = $gateId
            source = $Source
            attempt_id = $attemptId
            implementation_contract_raw_sha256 = Get-R23D3RawSha256 $implementationPath
            freeze_cas = $freezeCas
            stage_a_authorization_cas = $stageAAuthorizationCas
            stage_b_authorization_cas = $stageBAuthorizationCas
            stage_a_manifest_cas = $stageAManifestCas
            stage_b_manifest_cas = $stageBManifestCas
            stage_a_evaluation_cas = $stageAEvaluationCas
            complete_evaluation_cas = $completeEvaluationCas
            ordered_stage_a_cells = @($stageACells)
            ordered_stage_b_cells = @($stageBCells)
            stage_a_evaluation = $stageAEvaluationResult.evaluation
            complete_evaluation = $completeResult.evaluation
            selected_onset_id = $selectedOnset
            stage_b_launched = $stageBCells.Count -gt 0
            stage_a_world_count = 8
            stage_b_world_count = $stageBCells.Count
            result_classification = $classification
            development_result_valid = $validResult
            claims = [ordered]@{
                development_screen_only = $true
                command_conditioned_turning = $false
                bilateral_signed_turning = $false
                portable_basic_turning = $false
                cross_engine_equivalence = $false
                q_sdk_r23_satisfied = $false
                release_authorized = $false
                physical_acceptance_authority = $false
            }
        }
        $reportPath = Join-Path $resolvedOutput "report.json"
        Write-R23D3NewJson -Path $reportPath -Value $report
        $reportCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $reportPath `
            -MediaType "application/json"
        $completion = [ordered]@{
            schema_version = "sporespore_qsdk_r23d3_completion_v1"
            campaign_id = $campaignId
            gate_id = $gateId
            status = if ($validResult) {
                "$classification`_first_attempt"
            } else { "invalid_or_incomplete_first_attempt" }
            source_commit = [string]$Source.commit
            attempt_id = $attemptId
            selected_onset_id = $selectedOnset
            stage_a_terminal_entry_count = $stageACells.Count
            stage_b_terminal_entry_count = $stageBCells.Count
            result_classification = $classification
            report_cas = $reportCas
            one_shot_identity_consumed = $true
            same_identity_rerun_allowed = $false
            q_sdk_r23_satisfied = $false
            cross_engine_equivalence = $false
            release_authorized = $false
            physical_acceptance_authority = $false
        }
        Write-R23D3NewJson -Path $completionPath -Value $completion
        $completionCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $completionPath `
            -MediaType "application/json"
        Write-Host (
            "QSDK_R23D3_PHYSICAL_COMPLETE classification=$classification " +
            "selected_onset=$selectedOnset stage_a_cells=$($stageACells.Count) " +
            "stage_b_cells=$($stageBCells.Count) " +
            "report_sha256=$([string]$reportCas.sha256) " +
            "completion_sha256=$([string]$completionCas.sha256) " +
            "turning=False equivalence=False release=False"
        )
        if (-not $validResult) {
            throw "QSDK-R23D3 retained an invalid or incomplete first attempt: $resolvedOutput"
        }
    } catch {
        if ($attemptConsumed -and -not (Test-Path -LiteralPath $completionPath)) {
            $emergency = [ordered]@{
                schema_version = "sporespore_qsdk_r23d3_completion_v1"
                campaign_id = $campaignId
                gate_id = $gateId
                status = "invalid_or_incomplete_first_attempt"
                source_commit = [string]$Source.commit
                failure_code = "SUPERVISOR_INFRASTRUCTURE_EXCEPTION"
                failure_detail = $_.Exception.Message
                one_shot_identity_consumed = $true
                same_identity_rerun_allowed = $false
                q_sdk_r23_satisfied = $false
                cross_engine_equivalence = $false
                release_authorized = $false
                physical_acceptance_authority = $false
            }
            Write-R23D3NewJson -Path $completionPath -Value $emergency
            [void](Publish-SporeSporeContentAddressedArtifact `
                -RepoRoot $repoRoot -ArtifactPath $completionPath `
                -MediaType "application/json")
        }
        throw
    }
}

