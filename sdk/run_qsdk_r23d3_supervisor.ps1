        campaign_id = $campaignId
        gate_id = $gateId
        implementation_contract_raw_sha256 = Get-R23D3RawSha256 $implementationPath
        declared_source_binding_count = $declaredPaths.Count
        stage_zero_gate_pass_count = 1
        worker_gate_pass_count = 3
        production_evaluator_test_count = 10
        physical_authorization_refusal_count = 1
        stage_a_declared_cell_count = 8
        stage_b_declared_cell_count_if_selected = 9
        possible_worker_identity_count = 44
        exact_controller_horizon_step_count = 2992
        actual_physical_process_launch_count = 0
        actual_world_attempt_count = 0
        actual_world_build_count = 0
        physical_execution_authorized = $RunPhysical.IsPresent
        command_conditioned_turning = $false
        bilateral_signed_turning = $false
        portable_basic_turning = $false
        cross_engine_equivalence = $false
        q_sdk_r23_satisfied = $false
        release_authorized = $false
        physical_acceptance_authority = $false
    }
    Write-Host (
        "QSDK_R23D3_SUPERVISOR_PREFLIGHT " +
        ($receipt | ConvertTo-Json -Depth 100 -Compress)
    )
    Write-Host (
        "QSDK_R23D3_SUPERVISOR_PASS stage_zero=1 workers=3 " +
        "evaluator_tests=10 physical_refusal=1 stage_a_cells=8 " +
        "stage_b_cells=9 possible_identities=44 horizon=2992 " +
        "actual_worlds=0 physical_authority=False"
    )
    if ($RunPhysical) {
        Invoke-R23D3PhysicalCampaign `
            -Source $physicalSource `
            -Attestation $physicalAttestation `
            -ZeroWorldReceipt $receipt `
            -Implementation $implementation
    }
} finally {
    if (Test-Path -LiteralPath $scratchRoot -PathType Container) {
        Remove-Item -LiteralPath $scratchRoot -Recurse -Force
    }
    if ($null -ne $operationLock) {
        Exit-SporeSporeLocomotionOperationLock $operationLock
    }
}
