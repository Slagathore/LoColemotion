function Get-R23D3SourceBindingPaths {
    param([Parameter(Mandatory)]$Implementation)
    $paths = [Collections.Generic.List[string]]::new()
    foreach ($path in @($Implementation.source_binding_policy.exact_paths)) {
        $paths.Add(([string]$path).Replace("\", "/"))
    }
    foreach ($prefix in @($Implementation.source_binding_policy.tracked_prefixes)) {
        $expanded = @((Invoke-R23D3Git @("ls-files", "--", [string]$prefix)) -split "`n" |
            Where-Object { -not [string]::IsNullOrWhiteSpace($_) })
        Assert-R23D3Exact ($expanded.Count -gt 0) (
            "QSDK-R23D3 source prefix expanded to zero files: $prefix"
        )
        foreach ($path in $expanded) { $paths.Add($path.Replace("\", "/")) }
    }
    $duplicates = @($paths | Group-Object | Where-Object Count -gt 1)
    $duplicateNames = @(
        $duplicates | ForEach-Object { [string]$_.Name }
    )
    Assert-R23D3Exact ($duplicates.Count -eq 0) (
        "QSDK-R23D3 source binding paths contain duplicates: " +
        ($duplicateNames -join ",")
    )
    return @($paths)
}

function Get-R23D3SourceBindings {
    param([Parameter(Mandatory)]$Implementation)
    $paths = @(Get-R23D3SourceBindingPaths $Implementation)
    $bindings = [Collections.Generic.List[object]]::new()
    foreach ($relativePath in $paths) {
        $absolutePath = Join-Path $repoRoot $relativePath
        Assert-R23D3Exact (Test-Path -LiteralPath $absolutePath -PathType Leaf) (
            "QSDK-R23D3 source binding is missing: $relativePath"
        )
        $trackedOid = Invoke-R23D3Git @("rev-parse", "HEAD:$relativePath")
        $rawOid = Invoke-R23D3Git @(
            "hash-object", "--no-filters", "--", $relativePath
        )
        Assert-R23D3Exact ($trackedOid -ceq $rawOid) (
            "QSDK-R23D3 checkout bytes differ from the Git blob: $relativePath"
        )
        $bindings.Add([ordered]@{
            path = $relativePath
            raw_sha256 = Get-R23D3RawSha256 $absolutePath
            git_blob_oid = $trackedOid
            raw_checkout_equals_git_blob = $true
            media_type = Get-R23D3MediaType $relativePath
        })
    }
    return @($bindings)
}

function Assert-R23D3FrozenBindings {
    param([Parameter(Mandatory)]$Freeze)
    foreach ($binding in @($Freeze.source_bindings)) {
        $path = Join-Path $repoRoot ([string]$binding.path)
        Assert-R23D3Exact (
            (Test-Path -LiteralPath $path -PathType Leaf) -and
            [string]$binding.raw_sha256 -ceq (Get-R23D3RawSha256 $path) -and
            [string]$binding.git_blob_oid -ceq
                (Invoke-R23D3Git @("rev-parse", "HEAD:$([string]$binding.path)")) -and
            [string]$binding.git_blob_oid -ceq
                (Invoke-R23D3Git @(
                    "hash-object", "--no-filters", "--", [string]$binding.path
                ))
        ) "QSDK-R23D3 frozen source binding changed: $([string]$binding.path)"
    }
    foreach ($runtime in @($Freeze.runtime_artifacts)) {
        $path = [IO.Path]::GetFullPath([string]$runtime.path)
        Assert-R23D3Exact (
            (Test-Path -LiteralPath $path -PathType Leaf) -and
            [string]$runtime.raw_sha256 -ceq (Get-R23D3RawSha256 $path)
        ) "QSDK-R23D3 runtime artifact changed: $path"
    }
    foreach ($runtime in @($Freeze.external_runtime_bindings)) {
        $path = [IO.Path]::GetFullPath([string]$runtime.path)
        Assert-R23D3Exact (
            (Test-Path -LiteralPath $path -PathType Leaf) -and
            [string]$runtime.raw_sha256 -ceq (Get-R23D3RawSha256 $path)
        ) "QSDK-R23D3 external runtime changed: $path"
    }
}

function Publish-R23D3BoundInputs {
    param(
        [Parameter(Mandatory)]$SourceBindings,
        [Parameter(Mandatory)]$RuntimeArtifacts,
        [Parameter(Mandatory)]$ExternalRuntimeBindings,
        [Parameter(Mandatory)][string]$AttestationPath
    )
    $sourceReceipts = [Collections.Generic.List[object]]::new()
    foreach ($binding in @($SourceBindings)) {
        $sourceReceipts.Add((Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath (Join-Path $repoRoot ([string]$binding.path)) `
            -MediaType ([string]$binding.media_type)))
    }
    $runtimeReceipts = [Collections.Generic.List[object]]::new()
    foreach ($runtime in @($RuntimeArtifacts)) {
        $runtimeReceipts.Add((Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath ([string]$runtime.path) `
            -MediaType ([string]$runtime.media_type)))
    }
    $externalReceipts = [Collections.Generic.List[object]]::new()
    foreach ($runtime in @($ExternalRuntimeBindings)) {
        $externalReceipts.Add((Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath ([string]$runtime.path) `
            -MediaType ([string]$runtime.media_type)))
    }
    $attestationReceipt = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $AttestationPath `
        -MediaType "application/json"
    return [ordered]@{
        source_bindings = @($sourceReceipts)
        runtime_artifacts = @($runtimeReceipts)
        external_runtime_bindings = @($externalReceipts)
        full_godot_attestation = $attestationReceipt
        physical_acceptance_authority = $false
    }
}

