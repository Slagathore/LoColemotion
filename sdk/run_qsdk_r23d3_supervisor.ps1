$scratchRoot = Join-Path $sdkRoot (
    "target\qsdk-r23d3-supervisor-preflight\" + [guid]::NewGuid().ToString("N")
)
[void][IO.Directory]::CreateDirectory($scratchRoot)
try {
    # Materialize all three local runtime entrypoints before the worker gates.
    # This is zero-world; the physical path repeats the build from its verified
    # clean commit and hashes those exact outputs into the runtime freeze.
    . $runtimeMaterializationPath
    $developmentCommit = Invoke-R23D3Git @("rev-parse", "HEAD")
    $developmentRuntime = Initialize-SporeSporeR23D3AttemptRuntimeArtifacts `
        -RepoRoot $repoRoot `
        -SourceCommit $developmentCommit `
        -TargetRoot (Join-Path $sdkRoot "target")
    Assert-R23D3Exact (
        [string]$developmentRuntime.source_commit -ceq $developmentCommit -and
        -not [bool]$developmentRuntime.physical_acceptance_authority
    ) "QSDK-R23D3 zero-world runtime materialization failed"

    $gateSpecs = @(
        [ordered]@{
            path = Join-Path $sdkRoot "run_qsdk_r23d3_phase_balanced_preflight.ps1"
            prefix = "QSDK_R23D3_STAGE_ZERO_PASS "
            arguments = @("-Python", $Python)
        },
        [ordered]@{
            path = Join-Path $sdkRoot "run_qsdk_r23d3_mujoco_worker_preflight.ps1"
            prefix = "QSDK_R23D3_MUJOCO_WORKER_PASS "
            arguments = @()
        },
        [ordered]@{
            path = Join-Path $sdkRoot "run_qsdk_r23d3_rapier_worker_preflight.ps1"
            prefix = "QSDK_R23D3_RAPIER_WORKER_PASS "
            arguments = @()
        },
        [ordered]@{
            path = Join-Path $sdkRoot "run_qsdk_r23d3_godot_jolt_worker_preflight.ps1"
            prefix = "QSDK_R23D3_GODOT_JOLT_WORKER_PASS "
            arguments = @("-Godot", $Godot)
        }
    )
    $gateResults = [Collections.Generic.List[object]]::new()
    foreach ($spec in $gateSpecs) {
        $gateResults.Add((Invoke-R23D3Gate `
            -Path ([string]$spec.path) `
            -PassPrefix ([string]$spec.prefix) `
            -AdditionalArguments @($spec.arguments)))
    }

    $evaluatorTests = Invoke-R23D3Process `
        -FileName $Python `
        -Arguments @(
            "-m", "unittest", "-v",
            "test_r23d3_physical_evaluator"
        ) `
        -WorkingDirectory (Join-Path $sdkRoot "turning") `
        -TimeoutSeconds 180
    if ($evaluatorTests.stdout) { Write-Host ([string]$evaluatorTests.stdout).TrimEnd() }
    if ($evaluatorTests.stderr) { Write-Host ([string]$evaluatorTests.stderr).TrimEnd() }
    Assert-R23D3Exact (
        -not [bool]$evaluatorTests.timed_out -and
        [int]$evaluatorTests.exit_code -eq 0
    ) "QSDK-R23D3 production evaluator tests failed"

    $physicalBypass = Invoke-R23D3Process `
        -FileName $PowerShell `
        -Arguments @(
            "-NoLogo", "-NoProfile", "-File", $PSCommandPath, "-RunPhysical"
        ) `
        -WorkingDirectory $repoRoot `
        -TimeoutSeconds 60
    Assert-R23D3Exact (
        -not [bool]$physicalBypass.timed_out -and
        [int]$physicalBypass.exit_code -ne 0
    ) "QSDK-R23D3 direct physical bypass did not refuse"
    $refusal = Get-R23D3JsonMarker `
        -Text $physicalBypass.stdout `
        -Prefix "QSDK_R23D3_PHYSICAL_REFUSAL "
    Assert-R23D3Exact (
        [string]$refusal.refusal_stage -ceq "before_attempt_or_world" -and
        [int]$refusal.physical_process_launch_count -eq 0 -and
        [int]$refusal.world_attempt_count -eq 0 -and
        [int]$refusal.world_build_count -eq 0 -and
        -not [bool]$refusal.physical_acceptance_authority
    ) "QSDK-R23D3 physical refusal receipt changed"

    $receipt = [ordered]@{
