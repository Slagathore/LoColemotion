        -FileName $resolvedPowerShellPath `
        -Arguments (@("-NoLogo", "-NoProfile", "-File", $Path) + $AdditionalArguments) `
        -WorkingDirectory $repoRoot `
        -TimeoutSeconds $GateTimeoutSeconds
    if ($result.stdout) { Write-Host ([string]$result.stdout).TrimEnd() }
    if ($result.stderr) { Write-Host ([string]$result.stderr).TrimEnd() }
