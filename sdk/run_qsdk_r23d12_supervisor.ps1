function Invoke-R23D12PhysicalCampaign {
    param(
        [Parameter(Mandatory)]$Source,
        [Parameter(Mandatory)]$Attestation,
        [Parameter(Mandatory)]$ZeroWorldReceipt,
        [Parameter(Mandatory)]$AuthorizationCanaryReceipt,
        [Parameter(Mandatory)]$Implementation
    )
    $sourceAfterPreflight = Get-SporeSporeAttestationSourceIdentity `
        -RepoRoot $repoRoot `
        -RequireCleanPushedLive
    Assert-R23D12Exact (
        [string]$sourceAfterPreflight.commit -ceq [string]$Source.commit -and
        [string]$sourceAfterPreflight.tree_git_oid -ceq [string]$Source.tree_git_oid
    ) "QSDK-R23D12 source changed during the zero-world gate"
    Assert-R23D12Exact (
        [string](Invoke-R23D12Git @("status", "--porcelain=v1", "--untracked-files=all")) `
            -ceq ""
    ) "QSDK-R23D12 physical source is not clean after the zero-world gate"

    $evidenceRoot = Get-SporeSporeArtifactEvidenceRoot -RepoRoot $repoRoot
    $prior = @()
    if (Test-Path -LiteralPath $evidenceRoot -PathType Container) {
        $prior = @(Get-ChildItem -LiteralPath $evidenceRoot -Directory |
            Where-Object {
                $_.Name -like "qsdk-r23d12-*" -and (
                    (Test-Path -LiteralPath (Join-Path $_.FullName "stage-a-authorization.json")) -or
                    (Test-Path -LiteralPath (Join-Path $_.FullName "completion.json"))
                )
            })
    }
    Assert-R23D12Exact ($prior.Count -eq 0) (
        "QSDK-R23D12 one-shot identity already exists; rerun is forbidden"
    )
    $resolvedOutput = if ([string]::IsNullOrWhiteSpace($OutputRoot)) {
        Join-Path $evidenceRoot (
            "qsdk-r23d12-" + [DateTime]::UtcNow.ToString("yyyyMMddTHHmmssZ")
        )
    } else { [IO.Path]::GetFullPath($OutputRoot) }
    $evidencePrefix = $evidenceRoot.TrimEnd("\", "/") +
        [IO.Path]::DirectorySeparatorChar
    Assert-R23D12Exact (
        $resolvedOutput.StartsWith(
            $evidencePrefix, [StringComparison]::OrdinalIgnoreCase
        ) -and
        -not (Test-Path -LiteralPath $resolvedOutput)
    ) "QSDK-R23D12 output must be a new directory under $evidenceRoot"
    [void][IO.Directory]::CreateDirectory($resolvedOutput)

    $attemptConsumed = $false
    $completionPath = Join-Path $resolvedOutput "completion.json"
    try {
        $materialization = Initialize-R23D12RuntimeArtifacts `
            -SourceCommit ([string]$Source.commit)
        $runtimeArtifacts = Get-R23D12RuntimeArtifacts $materialization
        $runtimeMap = [ordered]@{
            locomotion_core = [string]$materialization.artifacts.locomotion_core
            godot_adapter = [string]$materialization.artifacts.godot_adapter
            rapier_worker = [string]$materialization.artifacts.rapier_worker
        }
        $sourceBindings = Get-R23D12SourceBindings $Implementation
        $externalRuntimeBindings = Get-R23D12ExternalRuntimeBindings
        $inputCas = Publish-R23D12BoundInputs `
            -SourceBindings $sourceBindings `
            -RuntimeArtifacts $runtimeArtifacts `
            -ExternalRuntimeBindings $externalRuntimeBindings `
            -AttestationPath $FullConformanceAttestation

        $freeze = [ordered]@{
            schema_version = "sporespore_qsdk_r23d12_physical_freeze_v1"
            status = "frozen_supervisor_only_physical_authorized"
            campaign_id = $campaignId
            gate_id = $gateId
            preregistration_raw_sha256 = Get-R23D12RawSha256 $preregistrationPath
            implementation_contract_raw_sha256 = Get-R23D12RawSha256 $implementationPath
            source_commit = [string]$Source.commit
            source_tree_git_oid = [string]$Source.tree_git_oid
            origin_main_commit = [string]$Source.origin_main
            live_github_main_commit = [string]$Source.live_github_main
            source_bindings = $sourceBindings
            runtime_artifacts = $runtimeArtifacts
            external_runtime_bindings = $externalRuntimeBindings
            runtime_materialization = $materialization
            content_addressed_inputs = $inputCas
            full_godot_attestation_sha256 = [string]$Attestation.sha256
            production_authorization_canaries_valid = $true
            production_authorization_canaries = $AuthorizationCanaryReceipt
            complete_zero_world_gate_passed = $true
            zero_world_receipt = $ZeroWorldReceipt
            declared_stage_a_world_count = 2
            declared_stage_b_world_count_if_selected = 9
            serial_execution_required = $true
            single_supervisor_attempt_required = $true
            stage_a_reports_may_substitute_for_stage_b = $false
            replacement_or_selective_rerun_permitted = $false
            source_checkout_bytes_equal_git_blobs = $true
            reproducible_runtime_materialization_passed = $true
            physical_execution_authorized = $true
            physical_acceptance_authority = $false
        }
        $freezePath = Join-Path $resolvedOutput "physical-freeze.json"
        Write-R23D12NewJson -Path $freezePath -Value $freeze
        $freezeCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot `
            -ArtifactPath $freezePath `
            -MediaType "application/json"
        Assert-R23D12FrozenBindings $freeze

        $attemptId = [guid]::NewGuid().ToString("N")
        $stageAToken = [guid]::NewGuid().ToString("N")
        $stageAAuthorizationPath = Join-Path $resolvedOutput "stage-a-authorization.json"
        $stageAAuthorizationCas = New-R23D12StageAuthorization `
            -Path $stageAAuthorizationPath `
            -AttemptId $attemptId `
            -Token $stageAToken `
            -SourceCommit ([string]$Source.commit) `
            -FreezeSha256 ([string]$freezeCas.sha256) `
            -AttemptRoot $resolvedOutput `
            -OrderedStageACellIds $stageACellIds `
            -OrderedStageBCellIds @() `
            -SelectedRestorationPolicyId "UNSELECTED" `
            -StageAuthorizationId "stage_a" `
            -InputCas $inputCas `
            -ZeroWorldReceipt $ZeroWorldReceipt `
            -AuthorizationCanaryReceipt $AuthorizationCanaryReceipt `
            -AttestationSha256 ([string]$Attestation.sha256)
        $attemptConsumed = $true

        $stageACells = [Collections.Generic.List[object]]::new()
        foreach ($cellId in $stageACellIds) {
            $parts = $cellId -split "__", 3
            $stageACells.Add((Invoke-R23D12PhysicalCell `
                -StageId $stageAId `
                -EngineId "mujoco" `
                -ArmId $parts[2] `
                -SourceCommit ([string]$Source.commit) `
                -FreezePayloadPath ([string]$freezeCas.payload_path) `
                -AttemptPayloadPath ([string]$stageAAuthorizationCas.payload_path) `
                -Token $stageAToken `
                -AttemptRoot $resolvedOutput `
                -CellRoot (Join-Path $resolvedOutput ("stage-a\" + $cellId)) `
                -RuntimeArtifacts $runtimeMap `
                -Freeze $freeze))
        }
        $stageAPaths = @($stageACells | ForEach-Object {
            [string]$_.terminal_entry_cas.payload_path
        })
        $stageAManifestPath = Join-Path $resolvedOutput "stage-a-terminal-paths.json"
        Write-R23D12Manifest -Path $stageAManifestPath -Paths $stageAPaths
        $stageAManifestCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $stageAManifestPath `
            -MediaType "application/json"
        $stageAEvaluationResult = Invoke-R23D12Evaluation `
            -Kind "stage-a" `
            -EvaluationRoot (Join-Path $resolvedOutput "stage-a-evaluator") `
            -StageAManifest ([string]$stageAManifestCas.payload_path) `
            -ExpectedSourceCommit ([string]$Source.commit)

        $stageBCells = [Collections.Generic.List[object]]::new()
        $stageBAuthorizationCas = $null
        $selectedPolicy = [string](
            $stageAEvaluationResult.evaluation.selected_terminal_policy_id
        )
        if ([bool]$stageAEvaluationResult.evaluation.stage_b_launch_authorized) {
            Assert-R23D12Exact (
                [bool]$stageAEvaluationResult.evaluation.valid -and
                $selectedPolicy -ceq $selectedQuiescentTaperPolicyId -and
                [int]$stageAEvaluationResult.process.exit_code -eq 0
            ) "QSDK-R23D12 Stage B authorization state is inconsistent"
            $stageBCellIds = Get-R23D12StageBCellIds
            $stageBToken = [guid]::NewGuid().ToString("N")
            $stageBAuthorizationPath = Join-Path `
                $resolvedOutput `
                "stage-b-authorization.json"
            $stageBAuthorizationCas = New-R23D12StageAuthorization `
                -Path $stageBAuthorizationPath `
                -AttemptId $attemptId `
                -Token $stageBToken `
                -SourceCommit ([string]$Source.commit) `
                -FreezeSha256 ([string]$freezeCas.sha256) `
                -AttemptRoot $resolvedOutput `
                -OrderedStageACellIds $stageACellIds `
                -OrderedStageBCellIds $stageBCellIds `
                -SelectedRestorationPolicyId $selectedPolicy `
                -StageAuthorizationId "stage_b" `
                -InputCas $inputCas `
                -ZeroWorldReceipt $ZeroWorldReceipt `
                -AuthorizationCanaryReceipt $AuthorizationCanaryReceipt `
                -AttestationSha256 ([string]$Attestation.sha256) `
                -ParentAuthorizationSha256 ([string]$stageAAuthorizationCas.sha256)
            foreach ($cellId in $stageBCellIds) {
                $parts = $cellId -split "__", 3
                $stageBCells.Add((Invoke-R23D12PhysicalCell `
                    -StageId $stageBId `
                    -EngineId $parts[0] `
                    -ArmId $parts[2] `
                    -SourceCommit ([string]$Source.commit) `
                    -FreezePayloadPath ([string]$freezeCas.payload_path) `
                    -AttemptPayloadPath ([string]$stageBAuthorizationCas.payload_path) `
                    -Token $stageBToken `
                    -AttemptRoot $resolvedOutput `
