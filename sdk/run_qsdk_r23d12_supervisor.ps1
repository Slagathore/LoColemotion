        "QSDK_R23D12_SUPERVISOR_PREFLIGHT " +
        ($receipt | ConvertTo-Json -Depth 100 -Compress)
    )
    Write-Host (
        "QSDK_R23D12_SUPERVISOR_PASS runtime_materialization=1 external_runtimes=4 " +
        "lineage_closures=3 dependency_marker=1 authorization_canary_preflight=1 " +
