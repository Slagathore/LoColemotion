function Invoke-R23D12Evaluation {
    param(
        [Parameter(Mandatory)][ValidateSet("stage-a", "complete")]
        [string]$Kind,
        [Parameter(Mandatory)][string]$EvaluationRoot,
        [Parameter(Mandatory)][string]$StageAManifest,
        [Parameter(Mandatory)][string]$ExpectedSourceCommit,
        [string]$StageBManifest = ""
    )
    if ($Kind -ceq "stage-a") {
        $arguments = @(
            $evaluatorPath, "evaluate-stage-a", "--manifest", $StageAManifest,
            "--expected-source-commit", $ExpectedSourceCommit
        )
        $prefix = "QSDK_R23D12_STAGE_A_EVALUATION "
    } else {
        $arguments = @(
            $evaluatorPath, "evaluate-complete",
            "--stage-a-manifest", $StageAManifest,
            "--stage-b-manifest", $StageBManifest,
            "--expected-source-commit", $ExpectedSourceCommit
        )
        $prefix = "QSDK_R23D12_COMPLETE_EVALUATION "
    }
    $result = Invoke-R23D12Process `
        -FileName $resolvedPythonPath `
        -Arguments $arguments `
        -WorkingDirectory $repoRoot `
        -TimeoutSeconds 300
    [void][IO.Directory]::CreateDirectory($EvaluationRoot)
    $stdoutPath = Join-Path $EvaluationRoot "stdout.txt"
    $stderrPath = Join-Path $EvaluationRoot "stderr.txt"
    $processPath = Join-Path $EvaluationRoot "process.json"
    [IO.File]::WriteAllText(
        $stdoutPath, [string]$result.stdout, [Text.UTF8Encoding]::new($false)
    )
    [IO.File]::WriteAllText(
        $stderrPath, [string]$result.stderr, [Text.UTF8Encoding]::new($false)
    )
    Write-R23D12NewJson -Path $processPath -Value ([ordered]@{
        schema_version = "sporespore_qsdk_r23d12_evaluator_process_v1"
        kind = $Kind
        exit_code = [int]$result.exit_code
        timed_out = [bool]$result.timed_out
        duration_seconds = [double]$result.duration_seconds
        stage_a_manifest = $StageAManifest
        stage_b_manifest = $StageBManifest
        expected_source_commit = $ExpectedSourceCommit
        physical_acceptance_authority = $false
    })
    $stdoutCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot -ArtifactPath $stdoutPath -MediaType "text/plain"
    $stderrCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot -ArtifactPath $stderrPath -MediaType "text/plain"
    $processCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot -ArtifactPath $processPath -MediaType "application/json"
    Assert-R23D12Exact (-not [bool]$result.timed_out) (
        "QSDK-R23D12 evaluator timed out: $Kind"
    )
    Assert-R23D12Exact ([int]$result.exit_code -eq 0) (
        "QSDK-R23D12 evaluator exited nonzero after retention: $Kind"
    )
    Assert-R23D12Exact (
        -not ([string]$result.stdout).Contains(
            "QSDK_R23D12_EVALUATION ", [StringComparison]::Ordinal
        )
    ) "QSDK-R23D12 evaluator emitted the forbidden generic marker: $Kind"
    $evaluation = Get-R23D12JsonMarker -Text $result.stdout -Prefix $prefix
    $evaluationPath = Join-Path $EvaluationRoot "evaluation.json"
    Write-R23D12NewJson -Path $evaluationPath -Value $evaluation
    $evaluationCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot -ArtifactPath $evaluationPath -MediaType "application/json"
    return [ordered]@{
        process = $result
        evaluation = $evaluation
        retention = [ordered]@{
            stdout = $stdoutCas
            stderr = $stderrCas
            process = $processCas
            output = $evaluationCas
        }
    }
}

function Invoke-R23D12PhysicalCell {
    param(
        [Parameter(Mandatory)][string]$StageId,
        [Parameter(Mandatory)][string]$EngineId,
        [Parameter(Mandatory)][string]$ArmId,
        [Parameter(Mandatory)][string]$SourceCommit,
        [Parameter(Mandatory)][string]$FreezePayloadPath,
        [Parameter(Mandatory)][string]$AttemptPayloadPath,
        [Parameter(Mandatory)][string]$Token,
        [Parameter(Mandatory)][string]$AttemptRoot,
        [Parameter(Mandatory)][string]$CellRoot,
        [Parameter(Mandatory)]$RuntimeArtifacts,
        [Parameter(Mandatory)]$Freeze
    )
    Assert-R23D12FrozenBindings $Freeze
    [void][IO.Directory]::CreateDirectory($CellRoot)
    $cellId = if ($StageId -ceq $stageAId) {
        "mujoco__stability_assisted_taper__$ArmId"
    } else {
        "$EngineId`__stability_assisted_taper__$ArmId"
    }
    $environment = [ordered]@{
        SPORESPORE_QSDK_R23D12_FREEZE = $FreezePayloadPath
        SPORESPORE_QSDK_R23D12_ATTEMPT = $AttemptPayloadPath
        SPORESPORE_QSDK_R23D12_TOKEN = $Token
        SPORESPORE_QSDK_R23D12_STAGE = $StageId
        SPORESPORE_QSDK_R23D12_CELL = $cellId
        SPORESPORE_QSDK_R23D12_ENGINE = $EngineId
        SPORESPORE_QSDK_R23D12_ATTEMPT_ROOT = $AttemptRoot
        SPORESPORE_QSDK_R23D12_PYTHON = $resolvedPythonPath
        SPORESPORE_QSDK_R23D12_POWERSHELL = $resolvedPowerShellPath
    }
    $fileName = ""
    $arguments = @()
    $workingDirectory = $repoRoot
    $successPrefix = ""
    $failurePrefix = ""
    $singleTerminalPrefix = ""
    if ($EngineId -ceq "godot_jolt") {
        $fileName = $Godot
        $environment.APPDATA = Join-Path $CellRoot "appdata"
        $environment.LOCALAPPDATA = Join-Path $CellRoot "localappdata"
        [void][IO.Directory]::CreateDirectory($environment.APPDATA)
        [void][IO.Directory]::CreateDirectory($environment.LOCALAPPDATA)
        $arguments = @(
            "--headless", "--path", $repoRoot,
            "--log-file", (Join-Path $CellRoot "godot.log"),
            "--script", $godotWorkerResource, "--",
            "--stage", $StageId, "--arm", $ArmId,
            "--source-commit", $SourceCommit
        )
        $singleTerminalPrefix = "QSDK_R23D12_GODOT_JOLT_TERMINAL "
    } elseif ($EngineId -ceq "rapier_parry") {
        $fileName = [string]$RuntimeArtifacts.rapier_worker
        $arguments = @(
            "physical",
            "--stage", $StageId, "--arm", $ArmId,
            "--source-commit", $SourceCommit
        )
        $singleTerminalPrefix = "QSDK_R23D12_RAPIER_TERMINAL "
    } elseif ($EngineId -ceq "mujoco") {
        $fileName = $mujocoPython
        $workingDirectory = $repoRoot
        $environment.SPORESPORE_LOCOMOTION_LIBRARY =
            [string]$RuntimeArtifacts.locomotion_core
        $environment.PYTHONPATH = (
            $mujocoRoot + [IO.Path]::PathSeparator + $pythonCoreRoot
        )
        $arguments = @(
            "-m", "sporespore_mujoco_adapter.qsdk_r23d12_stability_assisted_taper_physical",
            "physical", "--stage-id", $StageId, "--arm-id", $ArmId,
            "--source-commit", $SourceCommit
        )
        $singleTerminalPrefix = "QSDK_R23D12_TERMINAL "
    } else {
        throw "QSDK-R23D12 unknown physical engine: $EngineId"
    }

    Write-Host "QSDK_R23D12_CELL_BEGIN stage=$StageId cell=$cellId"
    $launchSucceeded = $false
    try {
        $result = Invoke-R23D12Process `
            -FileName $fileName `
            -Arguments $arguments `
            -WorkingDirectory $workingDirectory `
            -Environment $environment `
            -TimeoutSeconds $CellTimeoutSeconds
        $launchSucceeded = $true
    } catch {
        $result = [ordered]@{
            exit_code = -1
            timed_out = $false
            duration_seconds = 0.0
            stdout = ""
            stderr = "SUPERVISOR_PROCESS_START_EXCEPTION:$($_.Exception.Message)"
        }
    }
    $stdoutPath = Join-Path $CellRoot "stdout.txt"
    $stderrPath = Join-Path $CellRoot "stderr.txt"
    $processPath = Join-Path $CellRoot "process.json"
    [IO.File]::WriteAllText(
        $stdoutPath, [string]$result.stdout,
        [Text.UTF8Encoding]::new($false)
    )
    [IO.File]::WriteAllText(
        $stderrPath, [string]$result.stderr,
        [Text.UTF8Encoding]::new($false)
    )
    Write-R23D12NewJson -Path $processPath -Value ([ordered]@{
        schema_version = "sporespore_qsdk_r23d12_worker_process_v1"
        stage_id = $StageId
        cell_id = $cellId
        engine_id = $EngineId
        process_launch_succeeded = $launchSucceeded
        exit_code = [int]$result.exit_code
        timed_out = [bool]$result.timed_out
        duration_seconds = [double]$result.duration_seconds
        physical_acceptance_authority = $false
    })
    $stdoutCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot -ArtifactPath $stdoutPath -MediaType "text/plain"
    $stderrCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot -ArtifactPath $stderrPath -MediaType "text/plain"
    $processCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot -ArtifactPath $processPath -MediaType "application/json"
    $godotLogCas = $null
    $godotLogPath = Join-Path $CellRoot "godot.log"
    if (Test-Path -LiteralPath $godotLogPath -PathType Leaf) {
        $godotLogCas = Publish-SporeSporeContentAddressedArtifact `
            -RepoRoot $repoRoot -ArtifactPath $godotLogPath -MediaType "text/plain"
    }

    $familyId = switch -CaseSensitive ($EngineId) {
        "mujoco" { "mujoco_single_terminal_prefix" }
        "rapier_parry" { "rapier_single_terminal_prefix" }
        "godot_jolt" { "godot_jolt_single_terminal_prefix" }
        default { throw "QSDK-R23D12 unknown terminal marker family: $EngineId" }
    }
    $engineLogRequired = $EngineId -ceq "godot_jolt"
    $retentionComplete = (
        $null -ne $processCas -and
        $null -ne $stdoutCas -and
        $null -ne $stderrCas -and
        (-not $engineLogRequired -or $null -ne $godotLogCas)
    )
    $retentionReceipt = [ordered]@{
        schema_version = "sporespore_qsdk_r23d12_process_retention_receipt_v1"
        retained_before_marker_interpretation = $true
        process_raw_sha256 = [string]$processCas.sha256
        stdout_raw_sha256 = [string]$stdoutCas.sha256
        stderr_raw_sha256 = [string]$stderrCas.sha256
        engine_log_required = $engineLogRequired
        engine_log_raw_sha256 = if ($null -ne $godotLogCas) {
            [string]$godotLogCas.sha256
        } else { "" }
        all_retained_bytes_content_addressed = $retentionComplete
    }
    $classification = $null
    $terminal = $null
    $markerKind = "supervisor_process_failure"
    try {
        $classification = Get-R23D12TerminalMarkerClassification `
            -FamilyId $familyId `
            -Stdout ([string]$result.stdout) `
            -ExitCode ([int]$result.exit_code) `
            -RetentionReceipt $retentionReceipt
        if ($null -ne $classification.terminal_entry) {
            $terminal = $classification.terminal_entry
        }
        $markerKind = switch -CaseSensitive (
            [string]$classification.classification
        ) {
            "success" { "successful_report" }
            "worker_failure" { "worker_failure" }
            default { "supervisor_process_failure" }
        }
    } catch {
        $classification = [ordered]@{
            schema_version = "sporespore_qsdk_r23d12_terminal_marker_classifier_v1"
            family_id = $familyId
            classification = "supervisor_process_failure"
            failure_code = "R23D12_TERMINAL_CLASSIFIER_EXCEPTION"
            failure_detail = $_.Exception.Message
            recognized_marker_count = 0
            success_marker_count = 0
            failure_marker_count = 0
            malformed_marker_count = 0
            terminal_entry = $null
            physical_acceptance_authority = $false
        }
    }
    if ($null -eq $terminal -or $markerKind -ceq "supervisor_process_failure") {
        $terminal = [ordered]@{
            schema_version = "sporespore_qsdk_r23d12_supervisor_process_failure_v1"
            campaign_id = $campaignId
            gate_id = $gateId
            stage_id = $StageId
            cell_id = $cellId
            engine_id = $EngineId
            arm_id = $ArmId
            source_commit = $SourceCommit
            process_launch_succeeded = $launchSucceeded
            process_exit_code = [int]$result.exit_code
            process_timed_out = [bool]$result.timed_out
            terminal_marker_classification = $classification
            retention_receipt = $retentionReceipt
            world_attempt_count_known = $false
            world_build_count_known = $false
            physical_acceptance_authority = $false
        }
        $markerKind = "supervisor_process_failure"
    }
    $terminalPath = Join-Path $CellRoot "terminal-entry.json"
    Write-R23D12NewJson -Path $terminalPath -Value $terminal
    $terminalCas = Publish-SporeSporeContentAddressedArtifact `
        -RepoRoot $repoRoot `
        -ArtifactPath $terminalPath `
        -MediaType "application/json"
    Write-Host (
        "QSDK_R23D12_CELL_RETAINED stage=$StageId cell=$cellId " +
        "marker=$markerKind terminal_sha256=$([string]$terminalCas.sha256)"
    )
    return [ordered]@{
        stage_id = $StageId
        cell_id = $cellId
        engine_id = $EngineId
        arm_id = $ArmId
        process_launch_succeeded = $launchSucceeded
        process_exit_code = [int]$result.exit_code
        process_timed_out = [bool]$result.timed_out
        process_duration_seconds = [double]$result.duration_seconds
        terminal_marker_kind = $markerKind
        terminal_marker_classification = $classification
        terminal_entry_cas = $terminalCas
        stdout_cas = $stdoutCas
        stderr_cas = $stderrCas
        process_cas = $processCas
        godot_log_cas = $godotLogCas
        physical_acceptance_authority = $false
    }
}

