        $_.StartsWith($PassPrefix, [StringComparison]::Ordinal)
    }).Count
    Assert-R23D12Exact (
        -not [bool]$result.timed_out -and
        [int]$result.exit_code -eq 0 -and
        $markerCount -eq 1
    ) "QSDK-R23D12 zero-world gate failed: $Path"
    return $result
}

