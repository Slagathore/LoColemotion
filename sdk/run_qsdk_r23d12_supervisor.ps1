function Invoke-R23D12Process {
    param(
        [Parameter(Mandatory)][string]$FileName,
        [Parameter(Mandatory)][string[]]$Arguments,
        [Parameter(Mandatory)][string]$WorkingDirectory,
        [Collections.IDictionary]$Environment = @{},
        [int]$TimeoutSeconds = 900
    )
    $start = [Diagnostics.ProcessStartInfo]::new()
    $start.FileName = $FileName
    $start.WorkingDirectory = $WorkingDirectory
    $start.UseShellExecute = $false
    $start.CreateNoWindow = $true
    $start.RedirectStandardOutput = $true
    $start.RedirectStandardError = $true
    foreach ($name in $attemptEnvironmentNames) {
        [void]$start.Environment.Remove($name)
    }
    foreach ($entry in $Environment.GetEnumerator()) {
        $start.Environment[[string]$entry.Key] = [string]$entry.Value
    }
    foreach ($argument in $Arguments) { [void]$start.ArgumentList.Add($argument) }
    $process = [Diagnostics.Process]::new()
    $process.StartInfo = $start
    $timer = [Diagnostics.Stopwatch]::StartNew()
    Assert-R23D12Exact $process.Start() "QSDK-R23D12 failed to start $FileName"
    $stdoutTask = $process.StandardOutput.ReadToEndAsync()
    $stderrTask = $process.StandardError.ReadToEndAsync()
    $timedOut = $false
    $nextHeartbeat = 30.0
    while (-not $process.WaitForExit(1000)) {
        if ($timer.Elapsed.TotalSeconds -ge $nextHeartbeat) {
            Write-Host (
                "QSDK_R23D12_PROGRESS process=$([IO.Path]::GetFileName($FileName)) " +
                "elapsed_seconds=" + $timer.Elapsed.TotalSeconds.ToString(
                    "F1", [Globalization.CultureInfo]::InvariantCulture
                )
            )
            $nextHeartbeat += 30.0
        }
        if ($timer.Elapsed.TotalSeconds -ge $TimeoutSeconds) {
            $timedOut = $true
            try { $process.Kill($true) } catch { }
            [void]$process.WaitForExit(10000)
            break
        }
    }
    $timer.Stop()
    $result = [ordered]@{
        exit_code = if ($process.HasExited) { $process.ExitCode } else { -1 }
        timed_out = $timedOut
        duration_seconds = $timer.Elapsed.TotalSeconds
        stdout = $stdoutTask.GetAwaiter().GetResult()
        stderr = $stderrTask.GetAwaiter().GetResult()
    }
    $process.Dispose()
    return $result
}

function Get-R23D12JsonMarker {
    param(
        [Parameter(Mandatory)][string]$Text,
        [Parameter(Mandatory)][string]$Prefix
    )
    $lines = @($Text -split "`r?`n" | Where-Object {
        $_.StartsWith($Prefix, [StringComparison]::Ordinal)
    })
    Assert-R23D12Exact ($lines.Count -eq 1) (
        "QSDK-R23D12 expected one '$Prefix' marker, observed $($lines.Count)"
    )
    return $lines[0].Substring($Prefix.Length) |
        ConvertFrom-Json -AsHashtable -Depth 100
}

function Resolve-R23D12ApplicationPath {
    param(
        [Parameter(Mandatory)][string]$Command,
        [Parameter(Mandatory)][string]$Label
    )
    Assert-R23D12Exact (-not [string]::IsNullOrWhiteSpace($Command)) (
        "QSDK-R23D12 $Label command is empty"
    )
    $resolved = if ([IO.Path]::IsPathFullyQualified($Command)) {
        [IO.Path]::GetFullPath($Command)
    } else {
        $matches = @(Get-Command `
            -Name $Command `
            -CommandType Application `
            -All `
            -ErrorAction Stop)
        Assert-R23D12Exact ($matches.Count -gt 0) (
            "QSDK-R23D12 $Label command did not resolve: $Command"
        )
        $source = [string]$matches[0].Source
        Assert-R23D12Exact (
            -not [string]::IsNullOrWhiteSpace($source) -and
            -not $source.Contains("`r") -and
            -not $source.Contains("`n")
        ) "QSDK-R23D12 $Label first application path is invalid: $source"
        [IO.Path]::GetFullPath($source)
    }
    Assert-R23D12Exact (
        -not $resolved.Contains("`r") -and
        -not $resolved.Contains("`n") -and
        (Test-Path -LiteralPath $resolved -PathType Leaf)
    ) "QSDK-R23D12 $Label application is missing or invalid: $resolved"
    return $resolved
}

function Invoke-R23D12Gate {
    param(
        [Parameter(Mandatory)][string]$Path,
